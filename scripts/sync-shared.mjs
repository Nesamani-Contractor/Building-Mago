#!/usr/bin/env node
// Copies the shared rules (packages/shared/src) into the backend so Edge Functions (Deno) use
// exactly the same validation, link allow-list and quota logic as the app.
// Run after changing packages/shared:  node scripts/sync-shared.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/shared/src');
const dest = join(root, 'backend/supabase/functions/_shared/core');
mkdirSync(dest, { recursive: true });

for (const file of readdirSync(src).filter((f) => f.endsWith('.ts'))) {
  const code = readFileSync(join(src, file), 'utf8').replace(/from '(\.\/[^']+)'/g, "from '$1.ts'");
  writeFileSync(join(dest, file), `// GENERATED by scripts/sync-shared.mjs — edit packages/shared/src/${file} instead.\n${code}`);
  console.log(`synced ${file}`);
}
